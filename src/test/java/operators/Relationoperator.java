package operators;

public class Relationoperator {
    static void main(String[] args) {
        int number1 =5;
        int number2 = 10;
        System.out.println(number1==number2);
        System.out.println(number1!=number2);
        System.out.println(number1>number2);
        System.out.println(number1<number2);
        System.out.println(number1>=number2);
        System.out.println(number1<=number2);
    }
}
